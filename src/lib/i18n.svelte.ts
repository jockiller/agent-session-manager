class I18nManager {
  locale = $state<Locale>("zh-CN");

  constructor() {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("asm_locale") as Locale | null;
      if (saved && (saved === "zh-CN" || saved === "zh-TW" || saved === "en" || saved === "ja" || saved === "ko")) {
        this.locale = saved;
      } else {
        this.locale = detectSystemLocale();
      }
    }
  }

  setLocale(l: Locale) {
    this.locale = l;
    if (typeof window !== "undefined") {
      localStorage.setItem("asm_locale", l);
    }
  }

  t(key: string, params?: Record<string, string | number>): string {
    const dict = translations[this.locale] || translations["en"];
    let val = dict[key] || translations["en"][key] || key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        val = val.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return val;
  }
}

export const i18n = new I18nManager();
export const t = (key: string, params?: Record<string, string | number>) => i18n.t(key, params);
