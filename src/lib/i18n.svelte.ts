export type Locale = "zh-CN" | "zh-TW" | "en" | "ja" | "ko";

export interface LocaleOption {
  id: Locale;
  label: string;
}

export const supportedLocales: LocaleOption[] = [
  { id: "zh-CN", label: "简体中文" },
  { id: "zh-TW", label: "繁體中文" },
  { id: "en", label: "English" },
  { id: "ja", label: "日本語" },
  { id: "ko", label: "한국어" },
];

export function detectSystemLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || ""];
  for (const l of langs) {
    const lower = l.toLowerCase();
    if (lower.startsWith("zh-tw") || lower.startsWith("zh-hk") || lower.startsWith("zh-mo") || lower.includes("hant")) {
      return "zh-TW";
    }
    if (lower.startsWith("zh")) {
      return "zh-CN";
    }
    if (lower.startsWith("ja")) {
      return "ja";
    }
    if (lower.startsWith("ko")) {
      return "ko";
    }
    if (lower.startsWith("en")) {
      return "en";
    }
  }
  return "en"; // Default fallback to English for unsupported locales
}

